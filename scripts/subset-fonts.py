"""Generate local, unicode-ranged webfonts. Requires fonttools[woff] only to regenerate."""
from hashlib import sha256
import json
from pathlib import Path
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public/fonts/PretendardVariable.woff2"
OUTPUT = ROOT / "public/fonts/portfolio"
STYLES = ROOT / "src/styles/font-face.css"


def unicode_range(points):
    ranges = []
    start = end = None
    for value in sorted(points):
        if start is None:
            start = end = value
        elif value == end + 1:
            end = value
        else:
            ranges.append(f"U+{start:X}" + (f"-{end:X}" if end != start else ""))
            start = end = value
    if start is not None:
        ranges.append(f"U+{start:X}" + (f"-{end:X}" if end != start else ""))
    return ",".join(ranges)


font = TTFont(SOURCE)
supported = set(font.getBestCmap())
font.close()
sources = [(path, path.read_text(encoding="utf-8")) for path in (ROOT / "src").rglob("*")
           if path.suffix in {".md", ".astro", ".ts", ".tsx", ".mjs"}]
corpus = "".join(text for _, text in sources)
# Keep growing project articles out of the font downloaded by every Korean home.
interface = "".join(text for path, text in sources if path.suffix != ".md")
interface += "".join(text.split("---", 2)[1] for path, text in sources
                     if path.parent.name == "projects" and text.startswith("---"))
latin = {point for point in supported if point <= 0x24F or 0x2000 <= point <= 0x206F}
common = ({ord(char) for char in interface} & supported) - latin
content = ({ord(char) for char in corpus} & supported) - latin - common
remaining = sorted(supported - latin - common - content)
groups = [("latin", latin), ("common", common), ("content", content)]
groups += [(f"extra-{index // 512:02d}", set(remaining[index:index + 512]))
           for index in range(0, len(remaining), 512)]
OUTPUT.mkdir(parents=True, exist_ok=True)
previous = json.loads((OUTPUT / "manifest.json").read_text()) if (OUTPUT / "manifest.json").exists() else {"files": []}
records, faces = [], []
for label, points in groups:
    if not points:
        continue
    font = TTFont(SOURCE, recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    # Retain copyright/OFL, rename the derived font instead of reserved family names.
    for record in font["name"].names:
        if record.nameID in {1, 3, 4, 6, 16, 25}:
            name = "PortfolioSans" if record.nameID in {6, 25} else "Portfolio Sans"
            record.string = name.encode(record.getEncoding())
    font.flavor = "woff2"
    temporary = OUTPUT / (label + ".woff2")
    font.save(temporary)
    font.close()
    payload = temporary.read_bytes()
    filename = label + "-" + sha256(payload).hexdigest()[:10] + ".woff2"
    temporary.replace(OUTPUT / filename)
    ranges = unicode_range(points)
    records.append({"file": filename, "bytes": len(payload), "characters": len(points), "unicodeRange": ranges})
    faces.append("@font-face{font-family:'Portfolio Sans';font-style:normal;font-weight:45 920;font-display:swap;"
                 f"src:url('/fonts/portfolio/{filename}') format('woff2');unicode-range:{ranges};}}")
    print(label, len(points), len(payload), flush=True)

# Only retire this generator's earlier, content-hashed files inside its own folder.
current = {record["file"] for record in records}
for record in previous["files"]:
    filename = record["file"]
    if filename not in current and re.fullmatch(r"(?:latin|common|content|extra-\d+)-[0-9a-f]{10}\.woff2", filename):
        candidate = (OUTPUT / filename).resolve()
        if candidate.parent != OUTPUT.resolve():
            raise ValueError("Font output escaped its directory")
        candidate.unlink(missing_ok=True)
manifest = {"sourceBytes": SOURCE.stat().st_size, "sourceSha256": sha256(SOURCE.read_bytes()).hexdigest(), "files": records}
(OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
STYLES.write_text("/* Generated by scripts/subset-fonts.py; OFL: public/fonts/OFL.txt. */\n" + "\n".join(faces) + "\n", encoding="utf-8")
